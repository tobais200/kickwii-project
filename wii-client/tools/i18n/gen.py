#!/usr/bin/env python3
# Generates wii-client/source/i18n_table.c for KickWii.
# Sources, in priority order:
#   kick/k*.py        KickWii strings: K(spanish_key, en, fr, de, it, nl, pt, ja, zh_hans, ko)
#   tr/twich_base.json  strings shared with TwichWii v1.1 (same 11 columns as the table)
# zh-Hant is converted from zh-Hans with OpenCC (s2twp). Also writes cjk/chars.json for gen_cjk.py.
import os,sys,re,json,unicodedata
HERE=os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0,HERE)
from keys import keys
from opencc import OpenCC
_occ=OpenCC('s2twp')
def to_zt(z):
    t=_occ.convert(z)
    for a,b in (('二維碼','QR 碼'),('關注','追隨')): t=t.replace(a,b)
    return t
LANGS=['en','es','fr','de','it','nl','pt','ja','zh','zt','ko']
ks=keys()
K={}
def kfun(*a):
    if len(a)!=10: print('BAD ENTRY',repr(a[0])); sys.exit(1)
    if a[0] in K: print('DUP',repr(a[0]))
    K[a[0]]=a[1:]
for n in sorted(f for f in os.listdir(HERE+'/kick') if re.match(r'k\d+\.py$',f)):
    exec(open(HERE+'/kick/'+n,encoding='utf8').read(),{'K':kfun})
base=json.load(open(HERE+'/tr/twich_base.json',encoding='utf8'))
def norm(s): return ''.join(c for c in unicodedata.normalize('NFD',s) if unicodedata.category(c)!='Mn').lower().replace('twitchwii','kickwii').replace('twitch','kick')
bnorm={}
for k in base: bnorm.setdefault(norm(k),k)
def cjk_punct(s,L):
    # ASCII , and ? right after a CJK character -> full-width punctuation
    s=re.sub(r'(?<=[\u3040-\u30ff\u3400-\u9fff]),', '、' if L=='ja' else '，', s) if L in('ja','zh') else s
    s=re.sub(r'(?<=[\u3040-\u30ff\u3400-\u9fff\uac00-\ud7a3])\?', '？', s) if L in('ja','zh') else s
    return s
def rebrand(v): return v.replace('TwitchWii','KickWii').replace('twitchwii','kickwii').replace('Twitch','Kick')
tr={}; src={}
for k in ks:
    if k in K:
        en,fr,de,it,nl,pt,ja,zh,ko=K[k]; ja=cjk_punct(ja,'ja'); zh=cjk_punct(zh,'zh')
        tr[k]=[en,k,fr,de,it,nl,pt,ja,zh,to_zt(zh),ko]; src[k]='kick'
    elif k in base:
        tr[k]=list(base[k]); tr[k][1]=k; src[k]='base'
    elif norm(k) in bnorm:
        tr[k]=[rebrand(x) for x in base[bnorm[norm(k)]]]; tr[k][1]=k; src[k]='base~'
spec=re.compile(r'%[-+ #0]*(?:\d+|\*)?(?:\.(?:\d+|\*))?(?:hh|h|ll|l|z)?[diuxXsfcp%]')
def specs(s): return [x for x in spec.findall(s) if x!='%%']
ALLOWED=set(chr(c) for c in range(32,127))|set(chr(c) for c in range(160,256))|{'\n'}
errs=[]; CH={}
for k in ks:
    if k not in tr: errs.append('MISSING '+repr(k)); continue
    for L,x in zip(LANGS,tr[k]):
        if specs(x)!=specs(k): errs.append(f'FORMAT {L}: {k!r} -> {x!r}')
        if x.count('\n')!=k.count('\n'): errs.append(f'NEWLINES {L}: {k!r} -> {x!r}')
        if L in ('ja','zh','zt','ko'):
            CH.setdefault(L,set()).update(c for c in x if ord(c)>255)
            bad=[c for c in x if ord(c)<256 and c not in ALLOWED]
        else: bad=[c for c in x if c not in ALLOWED]
        if bad: errs.append(f'GLYPH {L} {bad}: {x!r}')
        if re.search(r'\b[r]c\d|\b[R][C]\b',x): errs.append('release-candidate tag '+x)
        if L not in('es',) and src[k]!='kick' and re.search('Twitch',x) and 'Twitch' not in k: errs.append('BRAND '+x)
unused=[k for k in K if k not in ks]
if unused: print('UNUSED kick entries:',unused,file=sys.stderr)
for e in errs: print(e)
if errs and '--force' not in sys.argv: print(len(errs),'errors'); sys.exit(1)
def lit(s):
    o=''
    for c in s.encode('utf8'):
        if c==ord('"'): o+='\\"'
        elif c==ord('\\'): o+='\\\\'
        elif c==10: o+='\\n'
        elif 32<=c<127: o+=chr(c)
        else: o+='\\%03o'%c
    return '"'+o+'"'
rows=sorted((k for k in ks if k in tr),key=lambda x:x.encode('utf8'))
with open(HERE+'/../../source/i18n_table.c','w') as f:
    f.write('/* Generated by tools/i18n/gen.py - do not edit by hand.\n * Key = Spanish source text (sorted bytewise). Columns: en, es(key), fr, de, it, nl, pt, ja, zh-Hans, zh-Hant, ko. */\n#include "i18n.h"\ntypedef struct { const char *es; const char *t[LANG_COUNT]; } i18n_entry_t;\nconst i18n_entry_t i18n_table[] = {\n')
    for k in rows:
        t=tr[k]
        # the Spanish column repeats the key: store NULL-free pointer to the same literal via the key itself
        f.write('{%s,{%s}},\n'%(lit(k),','.join(lit(x) for x in t)))
    f.write('};\nconst int i18n_table_n = %d;\n'%len(rows))
print('wrote',len(rows),'entries:',sum(1 for k in rows if src[k]=='kick'),'KickWii,',sum(1 for k in rows if src[k]!='kick'),'shared with TwichWii')
NAMES={'ja':'日本語','zh':'简体中文','zt':'繁體中文','ko':'한국어'}
STREAM_NAMES='日本語한국어中文'
allc=set(''.join(NAMES.values())+STREAM_NAMES)
json.dump({'sets':{L:sorted(CH.get(L,set())) for L in NAMES},'names':sorted(allc),'bigtxt':{L:'' for L in NAMES}},open(HERE+'/cjk/chars.json','w'),ensure_ascii=False)
for L in NAMES: print(L,len(CH.get(L,())),'glyphs')
